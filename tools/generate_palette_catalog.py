#!/usr/bin/env python3
"""Generate the documented and compiled palette-resource catalog."""

from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import Counter
from pathlib import Path


HEADER = ["Package", "Theme", "ResourceKey", "SourcePaletteKey", "SourceFile", "Line"]
RESOURCE_TAG = re.compile(r"<StaticResource\b(?P<attributes>[^>]*)>", re.DOTALL)
KEY_ATTRIBUTE = re.compile(r"\bx:Key\s*=\s*\"([^\"]+)\"")
SOURCE_ATTRIBUTE = re.compile(r"\bResourceKey\s*=\s*\"([^\"]+)\"")
BACKGROUND_KEY = re.compile(r"SemiColorBackground[0-4]\Z")
PALETTE_PREFIXES = ("SemiColorPrimary", "SemiColorSecondary", "SemiColorInformation")


def source_is_supported(key: str) -> bool:
    return (
        key.startswith(PALETTE_PREFIXES)
        or BACKGROUND_KEY.fullmatch(key) is not None
        or key in {"SemiColorNavBackground", "SemiColorOverlayBackground", "SemiBlue1"}
    )


def normalize_source(key: str) -> str:
    """Semi's Information shades are aliases of its Primary (Blue) ramp."""
    if key.startswith("SemiColorInformation"):
        return "SemiColorPrimary" + key[len("SemiColorInformation") :]
    return key


def collect_rows(package: str, root: Path, theme_root: Path) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for theme in ("Light", "Dark"):
        folder = theme_root / theme
        if not folder.is_dir():
            raise FileNotFoundError(f"Theme directory not found: {folder}")
        for source_file in sorted(folder.rglob("*.axaml")):
            content = source_file.read_text(encoding="utf-8-sig")
            display_path = f"{package}/{source_file.relative_to(root).as_posix()}"
            for match in RESOURCE_TAG.finditer(content):
                attributes = match.group("attributes")
                resource_match = KEY_ATTRIBUTE.search(attributes)
                source_match = SOURCE_ATTRIBUTE.search(attributes)
                if resource_match is None or source_match is None:
                    continue
                resource_key, source_key = resource_match.group(1), source_match.group(1)
                if not source_is_supported(source_key):
                    continue
                line = content.count("\n", 0, match.start()) + 1
                rows.append(
                    {
                        "Package": package.removesuffix(".Avalonia"),
                        "Theme": theme,
                        "ResourceKey": resource_key,
                        "SourcePaletteKey": source_key,
                        "SourceFile": display_path,
                        "Line": str(line),
                    }
                )
    return rows


def render_csv(rows: list[dict[str, str]]) -> str:
    from io import StringIO

    output = StringIO(newline="")
    writer = csv.DictWriter(output, fieldnames=HEADER, lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return output.getvalue()


def render_cs(rows: list[dict[str, str]]) -> str:
    targets = sorted(
        {
            (row["ResourceKey"], normalize_source(row["SourcePaletteKey"]))
            for row in rows
        }
    )
    lines = [
        "// <auto-generated />",
        "namespace Semi.Avalonia.Recolor;",
        "",
        "internal readonly record struct PaletteResourceTarget(string ResourceKey, string SourcePaletteKey);",
        "",
        "internal static class PaletteResourceCatalog",
        "{",
        "    // Сгенерировано tools/generate_palette_catalog.py по исходникам тем Semi и Ursa.",
        "    public static readonly PaletteResourceTarget[] Targets =",
        "    [",
    ]
    lines.extend(f'        new("{key}", "{source}"),' for key, source in targets)
    lines.extend(["    ];", "}", ""])
    return "\n".join(lines)


def render_markdown(rows: list[dict[str, str]]) -> str:
    counts = Counter((row["Package"], row["Theme"]) for row in rows)
    total = len(rows)
    unique = len({row["ResourceKey"] for row in rows})
    return f"""# Палитровые ресурсы Semi и Ursa

Каталог собирается из прямых ссылок ресурсов Light/Dark на палитровые токены Semi.
Информационные токены Semi являются алиасами основной синей рампы и перекрашиваются вместе с Primary.
Ресурс Ursa `SelectionListIndicatorBackground` использует `SemiBlue1`; библиотека заменяет его оттенком 1 рампы Primary.

| Пакет | Light | Dark |
| --- | ---: | ---: |
| Semi | {counts[("Semi", "Light")]} | {counts[("Semi", "Dark")]} |
| Ursa Semi | {counts[("Ursa", "Light")]} | {counts[("Ursa", "Dark")]} |
| **Всего** | **{total}** | |

В CSV находится {total} определений и {unique} уникальных ключей ресурсов. Каждая строка содержит исходный
палитровый токен, файл и номер строки. Список C# создаётся из этого же набора с нормализацией
`SemiColorInformation*` к соответствующей ступени `SemiColorPrimary*`.

Источники: `Semi.Avalonia/src/Semi.Avalonia/Themes/{{Light,Dark}}` и
`Ursa.Avalonia/src/Ursa.Themes.Semi/Themes/{{Light,Dark}}`.

Для обновления каталога запустите `python tools/generate_palette_catalog.py --semi-root ../Semi.Avalonia --ursa-root ../Ursa.Avalonia`.
Для проверки без изменения файлов добавьте `--check`.
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--semi-root", type=Path)
    parser.add_argument("--ursa-root", type=Path)
    parser.add_argument("--check", action="store_true", help="Fail if generated files are out of date.")
    args = parser.parse_args()

    repo = Path(__file__).resolve().parents[1]
    workspace = repo.parent
    semi_root = (args.semi_root or workspace / "Semi.Avalonia").resolve()
    ursa_root = (args.ursa_root or workspace / "Ursa.Avalonia").resolve()
    if not semi_root.is_dir():
        parser.error(f"Semi source checkout not found: {semi_root}")

    rows = collect_rows(
        "Semi.Avalonia",
        semi_root,
        semi_root / "src" / "Semi.Avalonia" / "Themes",
    )
    if ursa_root.is_dir():
        rows.extend(
            collect_rows(
                "Ursa.Avalonia",
                ursa_root,
                ursa_root / "src" / "Ursa.Themes.Semi" / "Themes",
            )
        )
    rows.sort(key=lambda row: (row["Package"], row["Theme"], row["ResourceKey"], row["SourceFile"], int(row["Line"])))

    outputs = {
        repo / "docs" / "palette-resource-catalog.csv": render_csv(rows),
        repo / "docs" / "palette-resource-catalog.md": render_markdown(rows),
        repo / "src" / "Semi.Avalonia.Recolor" / "PaletteResourceCatalog.cs": render_cs(rows),
    }
    stale = [path for path, content in outputs.items() if not path.exists() or path.read_text(encoding="utf-8-sig") != content]
    if args.check:
        if stale:
            print("Generated catalog files are stale:", *(str(path.relative_to(repo)) for path in stale), sep="\n  ", file=sys.stderr)
            return 1
        print("Palette catalog is up to date.")
        return 0

    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"Wrote {path.relative_to(repo)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
